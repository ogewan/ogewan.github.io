#!/usr/bin/env node
/**
 * Generates the Angular timeline's data + i18n surface from
 *   - config.json (timeline array — structural data, repo root)
 *   - manifest.json (optional — resolves UUID-string entries to project rows)
 *   - locales/{en,es}/timeline.json (chrome + per-id node strings)
 *
 * Emits two TypeScript modules:
 *   - src/generated/timeline-data.ts    → TIMELINE_NODES
 *   - src/generated/timeline-strings.ts → TIMELINE_LOCALES
 *
 * Both are committed (small diffs, easy to inspect, no first-clone surprises).
 *
 * Re-run via `pnpm --filter @portfolio/content generate:timeline`. The shell's
 * vite.config.ts also runs the generator on every build start and watches
 * config.json + the timeline locale files in dev so edits are reflected
 * without a manual step.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const CONTENT_ROOT = resolve(__dirname, '..');
const REPO_ROOT = resolve(CONTENT_ROOT, '..', '..');

const CONFIG_PATH = resolve(REPO_ROOT, 'config.json');
const MANIFEST_PATH = resolve(REPO_ROOT, 'manifest.json');
const LOCALE_PATHS = {
  en: resolve(CONTENT_ROOT, 'locales/en/timeline.json'),
  es: resolve(CONTENT_ROOT, 'locales/es/timeline.json'),
};
const OUT_DIR = resolve(CONTENT_ROOT, 'src/generated');
const OUT_DATA = resolve(OUT_DIR, 'timeline-data.ts');
const OUT_STRINGS = resolve(OUT_DIR, 'timeline-strings.ts');

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

const config = readJson(CONFIG_PATH);
const manifest = existsSync(MANIFEST_PATH) ? readJson(MANIFEST_PATH) : [];
const locales = {
  en: readJson(LOCALE_PATHS.en),
  es: readJson(LOCALE_PATHS.es),
};

const findManifestEntry = (uuid) => manifest.find((e) => e.uuid === uuid);

function computeWhen(start, end) {
  const startYear = start.slice(0, 4);
  if (!end) return `${startYear} — present`;
  const endYear = end.slice(0, 4);
  if (startYear === endYear) return startYear;
  return `${startYear} — ${endYear}`;
}

const timelineSrc = config.timeline ?? [];
const focusUuid = config.current_focus;

const nodes = [];
const nodeStrings = { en: {}, es: {} };
const warnings = [];

for (const entry of timelineSrc) {
  if (typeof entry === 'string') {
    // UUID string → look up manifest entry
    const m = findManifestEntry(entry);
    if (!m) {
      warnings.push(`timeline UUID ${entry} not found in manifest — skipping`);
      continue;
    }
    nodes.push({
      id: m.uuid,
      category: 'work',
      when: computeWhen(m.started_at, m.ended_at),
      startedAt: m.started_at,
      i18nKey: m.uuid,
      tags: (m.tech ?? []).slice(0, 3),
      current: focusUuid === m.uuid,
    });
    // Manifest data is single-language; use the same strings for en + es.
    const entryStrings = {
      title: m.title,
      body: m.summary,
      ...(m.role ? { role: m.role } : {}),
    };
    nodeStrings.en[m.uuid] = entryStrings;
    nodeStrings.es[m.uuid] = entryStrings;
  } else {
    // Inline object → locale strings come from the timeline locale files
    const id = entry.id;
    nodes.push({
      id,
      category: entry.category,
      when: computeWhen(entry.start, entry.end),
      startedAt: entry.start,
      i18nKey: id,
      tags: entry.tags ?? [],
      current: entry.current ?? false,
    });
    for (const locale of /** @type {const} */ (['en', 'es'])) {
      const localized = locales[locale]?.nodes?.[id];
      if (!localized) {
        warnings.push(`timeline node "${id}" missing strings in locale "${locale}"`);
        nodeStrings[locale][id] = { title: id, body: '' };
      } else {
        nodeStrings[locale][id] = {
          title: localized.title,
          body: localized.body,
          ...(entry.role ? { role: entry.role } : {}),
          ...(entry.org ? { org: entry.org } : {}),
        };
      }
    }
  }
}

mkdirSync(OUT_DIR, { recursive: true });

const banner = `// Auto-generated by packages/content/scripts/generate-timeline.mjs
// Source: config.json#timeline + manifest.json + locales/*/timeline.json
// Edit those files, not this one — re-run \`pnpm --filter @portfolio/content generate:timeline\`.
`;

const dataSource = `${banner}
import type { TimelineNode } from '../timeline-types.js';

export const TIMELINE_NODES: readonly TimelineNode[] = ${JSON.stringify(nodes, null, 2)} as const;
`;

const stringsPayload = {
  en: { nodes: nodeStrings.en, chrome: locales.en.chrome },
  es: { nodes: nodeStrings.es, chrome: locales.es.chrome },
};

const stringsSource = `${banner}
import type { TimelineLocaleDict } from '../timeline-types.js';

export const TIMELINE_LOCALES: Record<'en' | 'es', TimelineLocaleDict> = ${JSON.stringify(
  stringsPayload,
  null,
  2,
)};
`;

writeFileSync(OUT_DATA, dataSource, 'utf8');
writeFileSync(OUT_STRINGS, stringsSource, 'utf8');

const summary = `timeline-generator: ${nodes.length} nodes (${nodes.filter((n) => n.current).length} current) → ${OUT_DATA.replace(REPO_ROOT, '.')}, ${OUT_STRINGS.replace(REPO_ROOT, '.')}`;
console.log(summary);
if (warnings.length) {
  for (const w of warnings) console.warn(`  ⚠ ${w}`);
}
